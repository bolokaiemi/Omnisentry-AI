class TranslationEngine {
    constructor() {
        this.currentLang = localStorage.getItem("omni_lang") || "en";
    }

    init() {
        this.applyTranslations(this.currentLang);
        this.setupSelectors();
        
        // Listen for dynamic element translations
        window.addEventListener("omni-scan-rendered", () => {
            this.applyTranslations(this.currentLang);
        });
    }

    setupSelectors() {
        const selects = document.querySelectorAll(".lang-select");
        selects.forEach(select => {
            select.value = this.currentLang;
            select.addEventListener("change", (e) => {
                const lang = e.target.value;
                this.setLanguage(lang);
            });
        });
    }

    setLanguage(lang) {
        if (!TRANSLATIONS[lang]) return;
        this.currentLang = lang;
        localStorage.setItem("omni_lang", lang);
        
        // Synchronize all dropdowns in layout (header, footer, etc.)
        const selects = document.querySelectorAll(".lang-select");
        selects.forEach(select => select.value = lang);
        
        this.applyTranslations(lang);
        
        // Trigger event for third party components
        window.dispatchEvent(new CustomEvent("languagechanged", { detail: { lang: lang } }));
    }

    applyTranslations(lang) {
        const dict = TRANSLATIONS[lang] || TRANSLATIONS["en"];
        document.documentElement.lang = lang;

        // 1. Text translations
        const elements = document.querySelectorAll("[data-i18n]");
        elements.forEach(el => {
            const key = el.getAttribute("data-i18n");
            if (dict[key]) {
                // Keep html markup if present, else textContent
                if (el.children.length === 0) {
                    el.textContent = dict[key];
                } else {
                    // Try targeting text node only if we have children icons/badges we don't want to wipe
                    const textNode = Array.from(el.childNodes).find(node => node.nodeType === Node.TEXT_NODE);
                    if (textNode) {
                        textNode.textContent = dict[key];
                    } else {
                        // Safe fallback
                        el.innerHTML = el.innerHTML.replace(el.innerText, dict[key]);
                    }
                }
            }
        });

        // 2. Placeholder translations
        const inputs = document.querySelectorAll("[data-i18n-placeholder]");
        inputs.forEach(input => {
            const key = input.getAttribute("data-i18n-placeholder");
            if (dict[key]) {
                input.placeholder = dict[key];
            }
        });

        // 3. Translate dynamic loading strings (if applicable)
        const feedbackFeedEl = document.getElementById("feedback-feed");
        if (feedbackFeedEl) {
            const reviewsLoadingText = feedbackFeedEl.querySelector("[data-i18n='reviews_loading']");
            if (reviewsLoadingText && dict["reviews_loading"]) {
                reviewsLoadingText.textContent = dict["reviews_loading"];
            }
        }
    }

    translate(key, defaultVal = "") {
        const dict = TRANSLATIONS[this.currentLang] || TRANSLATIONS["en"];
        return dict[key] || defaultVal;
    }
}

// Global reference
window.omniI18n = new TranslationEngine();

document.addEventListener("DOMContentLoaded", () => {
    window.omniI18n.init();
});
